package com.michaelgrundvig.frc.world.config;

import io.soabase.recordbuilder.core.RecordBuilder;
import java.lang.annotation.ElementType;
import java.lang.annotation.Inherited;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a configuration record, which is then built by name through a builder generated at compile
 * time: {@code Body.builder().frameLength(...).frameWidth(...)...build()}.
 *
 * <p>The builder asks for every value the record can't do without, in order, by name, so one can't
 * be left out (the code doesn't compile) or land in the wrong place (every value is labeled where
 * it is written). A value a robot may not have isn't asked for: it's set by name after the rest, or
 * left out. An {@code Optional} left out is empty, and one given is given as its value ({@code
 * .cg(new Translation3d(0, 0, 0.15))}, not {@code .cg(Optional.of(...))}). A list left out is empty
 * where its record says it may be, with {@code @RecordBuilder.Initializer(value = "of", source =
 * List.class)}; any other list is asked for. The architecture tests make the builder the only way
 * to build one.
 *
 * <p>Generated by <a href="https://github.com/Randgalt/record-builder">RecordBuilder</a>; a record
 * {@code Name} gets {@code NameBuilder}, a nested record {@code Outer.Name} gets {@code
 * OuterNameBuilder}. {@code NameBuilder.builder(existing)} copies one to change a few values. A
 * record holding a list copies it, since the builder hands it on as it's given.
 */
@RecordBuilder.Template(
    options =
        @RecordBuilder.Options(
            builderMode = RecordBuilder.BuilderMode.STAGED_REQUIRED_ONLY,
            // An Optional left out is empty, and one given is given as its value: .joint(PIVOT).
            emptyDefaultForOptional = true,
            addConcreteSettersForOptional = RecordBuilder.ConcreteSettersForOptionalMode.ENABLED,
            // A list is asked for unless its record gives it a default, an initializer.
            skipStagingForInitializedComponents = true,
            addStaticBuilder = false, // no positional shortcut
            addClassRetainedGenerated = true)) // lets the coverage report skip generated code
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.TYPE)
@Inherited
public @interface ConfigRecord {}
