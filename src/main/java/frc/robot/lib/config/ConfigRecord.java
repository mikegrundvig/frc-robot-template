package frc.robot.lib.config;

import io.soabase.recordbuilder.core.RecordBuilder;
import java.lang.annotation.ElementType;
import java.lang.annotation.Inherited;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a configuration record, which is then built by name through a builder generated at compile
 * time: {@code Body.builder().frameLength(...).frameWidth(...)...build()}.
 *
 * <p>The builder asks for every value, in order, by name, so a value can't be left out (the code
 * doesn't compile) or land in the wrong place (every value is labeled where it is written). The
 * architecture tests make the builder the only way to build one.
 *
 * <p>Generated by <a href="https://github.com/Randgalt/record-builder">RecordBuilder</a>; a record
 * {@code Name} gets {@code NameBuilder}, a nested record {@code Outer.Name} gets {@code
 * OuterNameBuilder}. {@code NameBuilder.builder(existing)} copies one to change a few values.
 */
@RecordBuilder.Template(
    options =
        @RecordBuilder.Options(
            builderMode = RecordBuilder.BuilderMode.STAGED,
            addStaticBuilder = false, // no positional shortcut
            addClassRetainedGenerated = true, // lets the coverage report skip generated code
            useImmutableCollections = true))
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.TYPE)
@Inherited
public @interface ConfigRecord {}
